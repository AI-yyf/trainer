export function ConversationCandidate({
  type,
  whyNow,
  targetSkill,
  continueIn,
  autoGenerated,
  language = "en-US",
  onContinue,
  onDismiss,
}: ConversationCandidateProps) {
  const typeLabel = candidateLabels[language]?.[type] ?? type;
  const continueLabel = continueIn ? (continueLabels[language]?.[continueIn] ?? continueIn) : undefined;

  return (
    <div className="conversation-candidate" role="region" aria-label={typeLabel}>
      <div className="conversation-candidate__header">
        <span className="conversation-candidate__badge">{typeLabel}</span>
        {autoGenerated && (
          <span className="conversation-candidate__auto">
            {language === "zh-CN" ? "自动" : "Auto"}
          </span>
        )}
      </div>
      {whyNow && <p className="conversation-candidate__why">{whyNow}</p>}
      {targetSkill && (
        <p className="conversation-candidate__skill">
          {language === "zh-CN" ? "目标能力" : "Target skill"}: {targetSkill}
        </p>
      )}
      <div className="conversation-candidate__actions">
        {continueLabel && onContinue && (
          <button className="button button--accent button--micro" type="button" onClick={onContinue}>
            {continueLabel}
          </button>
        )}
        {onDismiss && (
          <button className="button button--ghost button--micro" type="button" onClick={onDismiss}>
            {language === "zh-CN" ? "忽略" : "Dismiss"}
          </button>
        )}
      </div>
    </div>
  );
}

