export function CoachActionStatus({
  kind,
  label,
  status = "active",
  resultLabel,
  detail,
}: CoachActionStatusProps) {
  const { t } = useTranslation();
  const [phase, setPhase] = useState<"visible" | "fading" | "removed">("visible");

  const resolvedLabel = label || t(kindToCopyKey[kind]) || kind;
  const resolvedResult = resultLabel || t(kindToDoneCopyKey[kind]) || resolvedLabel;

  useEffect(() => {
    if (status !== "completed") {
      setPhase("visible");
      return;
    }
    setPhase("visible");
    const fadeTimer = window.setTimeout(() => {
      setPhase("fading");
    }, 4000);
    return () => {
      window.clearTimeout(fadeTimer);
    };
  }, [status]);

  const handleAnimationEnd = useCallback(() => {
    if (phase === "fading") {
      setPhase("removed");
    }
  }, [phase]);

  const isActive = status === "active";
  const displayText = isActive || status === "failed" ? resolvedLabel : resolvedResult;
  const activity: CoachActivity = useMemo(() => ({
    id: `coach-action-${kind}`,
    kind,
    status,
    label: displayText,
    detail,
    timestamp: new Date().toISOString(),
  }), [kind, status, displayText, detail]);

  const isRemoved = phase === "removed";

  if (isRemoved) {
    return null;
  }

  return (
    <div
      className={`coach-action-wrapper ${phase === "fading" ? "coach-action-wrapper--fade" : ""}`}
      role="status"
      aria-live="polite"
      onAnimationEnd={handleAnimationEnd}
    >
      <CoachActionPill activity={activity} />
    </div>
  );
}

