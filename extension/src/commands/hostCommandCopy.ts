export type HostCommandCopyKey = keyof typeof HOST_COMMAND_COPY;

function readSettingResponseLanguage(): string | undefined {
  try {
    return vscode?.workspace?.getConfiguration?.('trainer')?.get<string>('coach.responseLanguage');
  } catch {
    return undefined;
  }
}

export function resolveHostCommandLanguage(
  context?: Pick<CommandContext, 'getHostState'> | null,
  explicitLanguage?: unknown,
): ComposerLanguage {
  if (isComposerLanguage(explicitLanguage)) {
    return explicitLanguage;
  }
  const workspaceLanguage = context?.getHostState?.()?.bootstrap?.memory?.workspace?.responseLanguage;
  if (isComposerLanguage(workspaceLanguage)) {
    return workspaceLanguage;
  }
  const configured = readSettingResponseLanguage();
  if (isComposerLanguage(configured)) {
    return configured;
  }
  let uiLang: ComposerLanguage | undefined;
  try {
    uiLang = hostUiLanguage();
  } catch {
    uiLang = undefined;
  }
  return uiLang ?? 'en-US';
}

export function hostCommandCopy(
  language: ComposerLanguage | undefined,
  key: HostCommandCopyKey,
  params?: Record<string, string | number>,
): string {
  const entry = HOST_COMMAND_COPY[key];
  let text: string = entry[language ?? 'en-US'] ?? entry['en-US'];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
